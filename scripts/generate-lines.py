# 역 별칭: API 의 statnNm 과 표기가 다를 수 있는 역
ALIASES = {
    "총신대입구": ["이수", "총신대입구(이수)"],
    "잠실새내": ["신천"],
    "olympic": [],
}

out = []
for line in LINES:
    stations = []
    for name in line["stations"]:
        st = {"name": name}
        if name in COORDS:
            lat, lng = COORDS[name]
            st["lat"] = lat
            st["lng"] = lng
        if name in ALIASES and ALIASES[name]:
            st["aliases"] = ALIASES[name]
        stations.append(st)
    out.append({
        "id": line["id"],
        "name": line["name"],
        "subwayId": line["subwayId"],
        "color": line["color"],
        "loop": line["loop"],
        "avgSecondsPerStation": line["avgSecondsPerStation"],
        "note": line["note"],
        "upTerminal": stations[0]["name"],
        "downTerminal": stations[-1]["name"],
        "stations": stations,
    })

path = "/home/user/Jinobald/src/data/lines.json"
with io.open(path, "w", encoding="utf-8") as f:
    json.dump(out, f, ensure_ascii=False, indent=2)
    f.write("\n")

total = sum(len(l["stations"]) for l in out)
withc = sum(1 for l in out for s in l["stations"] if "lat" in s)
print("생성 완료:", path)
for l in out:
    print("  %-6s %3d개역  %s ~ %s" % (l["name"], len(l["stations"]), l["upTerminal"], l["downTerminal"]))
print("총 %d개 역 항목, 좌표 보유 %d개 (%.1f%%)" % (total, withc, 100.0*withc/total))
